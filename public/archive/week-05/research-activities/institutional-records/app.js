(() => {
  const payload = window.MAKING_CENTER_DATA;
  const records = payload.records;
  const systems = ["WebCheckout", "PaperCut", "Store", "Reservation", "Waitlist", "Transaction"];
  const colors = {
    WebCheckout: "var(--purple)",
    PaperCut: "var(--blue)",
    Store: "var(--orange)",
    Reservation: "var(--green)",
    Waitlist: "var(--red)",
    Transaction: "var(--pink)",
  };

  const state = { selected: null, lang: "zh" };
  const timeline = document.getElementById("timeline");
  const pageEyebrow = document.getElementById("page-eyebrow");
  const pageTitle = document.getElementById("page-title");
  const pageLede = document.getElementById("page-lede");
  const plotTitle = document.getElementById("plot-title");
  const plotHint = document.getElementById("plot-hint");
  const stageLabel = document.getElementById("stage-label");
  const title = document.getElementById("record-title");
  const summary = document.getElementById("record-summary");
  const facts = document.getElementById("record-facts");

  const copy = {
    zh: {
      eyebrow: "机构记录 / 2024—2026",
      title: "Design Lab 如何记录我",
      lede: (count) => `<span id="total-records">${count}</span> 条由六个机构系统生成的记录。我进行了这些活动，但没有决定它们如何被记录。`,
      plotTitle: "机构记录时间线",
      plotHint: "左右滚动。点击任意一点查看记录。",
      timelineAria: "不同 Design Lab 系统在 2024 到 2026 年留下的记录时间线",
      emptyTitle: "选择一条记录",
      emptySummary: "点击时间线上的数据点查看详细信息。",
      detailLabel: "机构记录",
      recordedBy: "记录者",
      subject: "被记录者",
      sourceSystem: "来源系统",
      recordType: "记录类型",
    },
    en: {
      eyebrow: "INSTITUTIONAL RECORD / 2024—2026",
      title: "How the Design Lab Records Me",
      lede: (count) => `<span id="total-records">${count}</span> records generated by six institutional systems. I performed these activities, but I did not decide how they were recorded.`,
      plotTitle: "Institutional record timeline",
      plotHint: "Scroll across time. Select any dot to view its record.",
      timelineAria: "Timeline of records left by Design Lab systems from 2024 to 2026",
      emptyTitle: "Select a record",
      emptySummary: "Select a dot on the timeline to view its details.",
      detailLabel: "INSTITUTIONAL RECORD",
      recordedBy: "RECORDED BY",
      subject: "Subject",
      sourceSystem: "Source system",
      recordType: "Record type",
    },
  };

  const laneLabels = {
    zh: { WebCheckout: "WebCheckout", PaperCut: "PaperCut", Store: "商店订单", Reservation: "预约", Waitlist: "等候名单", Transaction: "交易" },
    en: { WebCheckout: "WebCheckout", PaperCut: "PaperCut", Store: "Store orders", Reservation: "Reservations", Waitlist: "Waitlist", Transaction: "Transactions" },
  };

  const factLabelEn = {
    "开始": "Start", "结束": "End", "系统时长": "System duration", "对象": "Object",
    "时间": "Time", "打印机": "Printer", "页数": "Pages", "文件类型": "File type", "金额": "Amount", "状态": "Status",
    "订单号": "Order ID", "商店": "Store", "订单类型": "Order type", "提交": "Submitted", "计划设备": "Planned equipment",
    "计划项目": "Planned project", "计划数量": "Planned quantity", "用途": "Use", "工位": "Station", "预计打印": "Planned prints",
    "纸张": "Paper", "结果": "Result", "类型": "Type", "余额": "Balance", "执行者": "Processed by",
  };

  const recordTypes = {
    zh: {
      WebCheckout: "设备与工具借用",
      PaperCut: "打印任务",
      Store: "商店订单",
      Reservation: "设备预约",
      Waitlist: "现场等候",
      Transaction: "账户交易",
    },
    en: {
      WebCheckout: "Equipment and tool checkout",
      PaperCut: "Print job",
      Store: "Store order",
      Reservation: "Equipment reservation",
      Waitlist: "Walk-in waitlist",
      Transaction: "Account transaction",
    },
  };

  function recordTitle(record) {
    if (state.lang === "zh") return record.title;
    if (record.system === "WebCheckout") return `${record.source} checkout / use record`;
    if (record.system === "PaperCut") return `${record.title.replace(" 打印记录", "")} print record`;
    if (record.system === "Store") return "Design Lab store order";
    if (record.system === "Reservation") return "Printer reservation";
    if (record.system === "Waitlist") return "Walk-in waitlist record";
    return "Account transaction";
  }

  function recordSummary(record) {
    if (state.lang === "zh") return record.summary;
    if (record.system === "PaperCut") return record.summary.replace(/(\d+) 页 · (\d+) 彩色页/, "$1 pages · $2 color pages");
    if (record.system === "Store") return record.summary.replace(/^订单 (\d+) · 导出中没有商品与价格$/, "Order $1 · items and price are absent from this export");
    if (record.system === "Waitlist") return record.summary.replace(/ · 计划 (\d+) 次$/, " · $1 planned prints");
    if (record.system === "Transaction") return record.summary.replace("余额", "balance");
    return record.summary;
  }

  function factValueEn(value) {
    return String(value)
      .replace(/([\d,]+) 分钟$/, "$1 minutes")
      .replace("printed", "printed")
      .replace("not printed", "not printed")
      .replace("canceled", "canceled")
      .replace("获得打印机", "printer received")
      .replace("未记录为获得", "not recorded as received");
  }

  function escapeHtml(value) {
    return String(value)
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;")
      .replaceAll("'", "&#039;");
  }

  function renderTimeline() {
    const oldScroll = timeline.querySelector(".timeline-scroll")?.scrollLeft || 0;
    const viewportWidth = Math.max(560, timeline.clientWidth - 138 || 900);
    const width = Math.max(3200, Math.round(viewportWidth * 3.2));
    const margin = { top: 42, right: 24, bottom: 42, left: 12 };
    const rowGap = 66;
    const height = margin.top + margin.bottom + rowGap * systems.length;
    const start = new Date(payload.summary.start).getTime();
    const end = new Date(payload.summary.end).getTime();
    const x = (date) => margin.left + ((new Date(date).getTime() - start) / (end - start)) * (width - margin.left - margin.right);
    const y = (system) => margin.top + systems.indexOf(system) * rowGap + 18;
    const yearTicks = [
      { date: new Date(2024, 1, 12), label: "2024" },
      { date: new Date(2025, 0, 1), label: "2025" },
      { date: new Date(2026, 0, 1), label: "2026" },
      { date: new Date(2026, 8, 24), label: "" },
    ];

    const labelMarkup = systems.map((system) => {
      const cy = y(system);
      return `<div class="timeline-label" style="top:${cy}px">${laneLabels[state.lang][system]} <strong>${payload.summary.counts[system]}</strong></div>`;
    }).join("");

    const laneMarkup = systems.map((system) => {
      const cy = y(system);
      return `<line class="lane-line" x1="${margin.left}" x2="${width - margin.right}" y1="${cy}" y2="${cy}"></line>`;
    }).join("");

    const tickMarkup = yearTicks.map((tick, index) => {
      const tx = Math.max(margin.left, Math.min(width - margin.right, x(tick.date)));
      const anchor = index === 0 ? "start" : index === yearTicks.length - 1 ? "end" : "middle";
      return `
        <line class="axis-line" x1="${tx}" x2="${tx}" y1="${margin.top - 20}" y2="${height - margin.bottom + 8}"></line>
        <text class="axis-label" text-anchor="${anchor}" x="${tx}" y="${height - 8}">${tick.label}</text>`;
    }).join("");

    const stacks = new Map();
    const markMarkup = records.map((record) => {
      const day = record.date.slice(0, 10);
      const stackKey = `${record.system}-${day}`;
      const level = stacks.get(stackKey) || 0;
      stacks.set(stackKey, level + 1);
      const cx = x(record.date);
      const cy = y(record.system) - Math.min(level, 5) * 7;
      const selected = state.selected && state.selected.id === record.id ? " is-selected" : "";
      return `<circle class="record-mark${selected}" data-id="${record.id}" tabindex="0" role="button" aria-label="${escapeHtml(recordTitle(record))}, ${escapeHtml(recordSummary(record))}" cx="${cx.toFixed(2)}" cy="${cy.toFixed(2)}" r="4.6" fill="${colors[record.system]}"></circle>`;
    }).join("");

    timeline.innerHTML = `<div class="timeline-labels" style="height:${height}px">${labelMarkup}</div><div class="timeline-scroll"><svg viewBox="0 0 ${width} ${height}" style="width:${width}px;height:${height}px">${tickMarkup}${laneMarkup}${markMarkup}</svg></div>`;
    timeline.querySelector(".timeline-scroll").scrollLeft = oldScroll;
    timeline.querySelectorAll(".record-mark").forEach((mark) => {
      const choose = () => selectRecord(mark.dataset.id);
      mark.addEventListener("click", choose);
      mark.addEventListener("keydown", (event) => {
        if (event.key === "Enter" || event.key === " ") {
          event.preventDefault();
          choose();
        }
      });
    });
  }

  function selectRecord(id) {
    state.selected = records.find((record) => record.id === id);
    renderTimeline();
    renderStage();
    document.querySelector(".record-stage").scrollIntoView({ behavior: "smooth", block: "nearest" });
  }

  function renderStage() {
    const record = state.selected;
    if (!record) return;
    facts.innerHTML = "";
    const text = copy[state.lang];
    stageLabel.textContent = `${text.recordedBy}: ${record.system.toUpperCase()}`;
    title.textContent = recordTitle(record);
    summary.textContent = recordSummary(record);
    const institutionalFacts = [
      [text.subject, "Yinan Xue"],
      [text.sourceSystem, `${record.system} / ${record.source}`],
      [text.recordType, recordTypes[state.lang][record.system]],
    ];
    const rawFacts = record.facts.map(([term, value]) => [state.lang === "zh" ? term : factLabelEn[term] || term, state.lang === "zh" ? value : factValueEn(value)]);
    facts.innerHTML = [...institutionalFacts, ...rawFacts].map(([term, value]) => `<div><dt>${escapeHtml(term)}</dt><dd>${escapeHtml(value)}</dd></div>`).join("");
  }

  function renderLanguage() {
    const text = copy[state.lang];
    const count = payload.summary.total.toLocaleString("en-US");
    document.documentElement.lang = state.lang === "zh" ? "zh-CN" : "en";
    pageEyebrow.textContent = text.eyebrow;
    pageTitle.textContent = text.title;
    pageLede.innerHTML = text.lede(count);
    plotTitle.textContent = text.plotTitle;
    plotHint.textContent = text.plotHint;
    timeline.setAttribute("aria-label", text.timelineAria);
    document.querySelectorAll(".language-option").forEach((button) => {
      const active = button.dataset.lang === state.lang;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-pressed", String(active));
    });
    if (state.selected) {
      renderStage();
    } else {
      stageLabel.textContent = text.detailLabel;
      title.textContent = text.emptyTitle;
      summary.textContent = text.emptySummary;
      facts.innerHTML = "";
    }
    renderTimeline();
  }

  document.querySelectorAll(".language-option").forEach((button) => {
    button.addEventListener("click", () => {
      state.lang = button.dataset.lang;
      renderLanguage();
    });
  });

  let resizeTimer;
  window.addEventListener("resize", () => {
    window.clearTimeout(resizeTimer);
    resizeTimer = window.setTimeout(renderTimeline, 100);
  });

  renderLanguage();
})();
